import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
const src = rel => fs.readFileSync(path.join(import.meta.dirname, '../src', rel), 'utf8');
const server = rel => fs.readFileSync(path.join(import.meta.dirname, '../../backend', rel), 'utf8');
const history = src('pages/customer/ServiceHistory.tsx');
const reviews = src('pages/customer/Reviews.tsx');
const shell = src('pages/showcase/ReferenceShell.tsx');
const bell = src('pages/showcase/CustomerNotificationBell.tsx');
const routes = server('routes/api.php');
const controller = server('app/Http/Controllers/Api/CustomerNotificationController.php');
assert.match(history,/reviewsByOrder\.get\(order\.id\)/,'Only exact-order reviews are shown');
assert.match(history,/InlineHistoryReview/,'Customer sees review and garage reply inline');
assert.match(history,/reviews\?orderId=\$\{order\.id\}/,'Unreviewed order routes to preselected rating form');
assert.match(history,/vehicleId/,'History supports vehicle filtering');
assert.match(reviews,/targetOrderId/,'Review page respects orderId deep link');
assert.match(shell,/<CustomerNotificationBell\/>/,'Bell replaces the top review CTA');
assert.doesNotMatch(shell,/v3ref-reviews-link/,'No orphan review CTA next to avatar');
assert.match(shell,/to="\/reviews"/,'Review remains reachable via account menu and footer');
assert.match(bell,/getCustomerNotifications\(/,'Bell loads real data');
assert.match(bell,/readCustomerNotification\(/,'Bell marks notification read only through API');
assert.match(controller,/where\('account_id', \$accountId\)/,'Notifications scoped to signed-in account');
assert.match(controller,/\$notification->account_id/,'Read endpoint checks ownership');
assert.match(routes,/me\/notifications/,'Notification endpoints registered');
console.log('PASS: History reviews by vehicle/order, targeted reviews, notifications bell, account privacy');
